"""Best-effort SSDT-GPIO for I2C-HID trackpads.

When a DSDT is available we decompile it (with the ``iasl`` SSDTTime already
fetched) and look for the touchpad: an I2C peripheral whose ``_CRS`` carries a
``GpioInt``. If exactly one confident candidate is found we render and compile
``SSDT-GPIO`` that re-asserts ``_STA`` and pins the interrupt; otherwise we hand
back a precise TODO (path + pin + controller) so the manual step is trivial.
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

# _HID / _CID values that mean "HID over I2C"
_HID_HINTS = ("PNP0C50", "ACPI0C50")

_TEMPLATE = '''\
// Generated by ocforge from the machine's DSDT. VERIFY the trackpad works;
// if not, this pin/controller is wrong -- redo it by hand.
DefinitionBlock ("", "SSDT", 2, "OCFORG", "GPIO", 0x00000000)
{
    External (%(path)s, DeviceObj)

    Scope (%(path)s)
    {
        Method (_STA, 0, NotSerialized)  // present, enabled, functioning
        {
            If (_OSI ("Darwin"))
            {
                Return (0x0F)
            }
            Return (Zero)
        }

        Name (RBUF, ResourceTemplate ()
        {
            GpioInt (Level, ActiveLow, ExclusiveAndWake, PullUp, 0x0000,
                "%(ctrl)s", 0x00, ResourceConsumer,,)
            {   // Pin list
                %(pin)s
            }
        })
    }
}
'''


@dataclass
class GpioFinding:
    path: str          # full ACPI path of the touchpad device
    pin: int
    controller: str     # GPIO controller ACPI path
    hid: str
    generated: Path | None = None   # compiled SSDT-GPIO.aml, if we made one

    def todo(self) -> str:
        made = f"; wrote {self.generated.name}" if self.generated else ""
        return (f"SSDT-GPIO: touchpad {self.path} ({self.hid}) -> GpioInt pin "
                f"0x{self.pin:02X} on {self.controller}{made}")


def _find_iasl(ssdttime_dir: Path) -> Path | None:
    names = ("iasl.exe", "iasl", "iasl-stable", "iasl-dev")
    for base in (ssdttime_dir / "Scripts", ssdttime_dir):
        for n in names:
            p = base / n
            if p.is_file():
                return p.resolve()
    return None


def _iasl(iasl: Path, work_dir: Path, args: list[str], timeout: int) -> None:
    """Run iasl with basename args so a relative ``work_dir`` can't double-nest."""
    subprocess.run([str(iasl), *args], cwd=str(work_dir.resolve()),
                   capture_output=True, text=True, timeout=timeout, check=False)


def _decompile(dsdt_dir: Path, iasl: Path) -> str | None:
    dsdt_dir = dsdt_dir.resolve()
    dsdt = dsdt_dir / "DSDT.aml"
    if not dsdt.is_file():
        return None
    ssdts = sorted(p.name for p in dsdt_dir.glob("SSDT*.aml"))
    args = ["-d"]
    if ssdts:
        args += ["-e", *ssdts]
    args.append("DSDT.aml")
    _iasl(iasl, dsdt_dir, args, timeout=120)
    dsl = dsdt.with_suffix(".dsl")
    return dsl.read_text(errors="replace") if dsl.is_file() else None


_GPIOINT = re.compile(
    r'GpioInt\s*\('           # opener
    r'[^)]*?"([^"]+)"'         # 1: GPIO controller path (first quoted arg)
    r'[^)]*?\)'               # ... rest of the descriptor args
    r'\s*\{[^}]*?'             # opening brace + any "// Pin list" comment
    r'(0x[0-9A-Fa-f]+|\d+)',   # 2: first pin number
    re.S,
)
_HID_RE = re.compile(
    r'_(?:HID|CID)\s*,\s*(?:"([^"]+)"|\w+\s*\(\s*"?([^")]+))'
)


def _abspath(stack: list[str], name: str) -> str | None:
    if name.startswith("^") or "^" in name:
        return None  # parent refs — don't guess
    if name.startswith("\\"):
        return name
    joined = ".".join(s.strip("\\") for s in [*stack, name] if s not in ("", "\\"))
    return "\\" + joined


def _scan(dsl: str) -> list[GpioFinding]:
    cands: list[GpioFinding] = []
    for dm in re.finditer(r'Device\s*\(\s*([\\^A-Za-z0-9_.]+)\s*\)\s*\{', dsl):
        start = dm.end()
        d, j = 1, start
        while j < len(dsl) and d:
            d += (dsl[j] == "{") - (dsl[j] == "}")
            j += 1
        body = dsl[start:j]
        # a peripheral, not a bus: it *consumes* an I2C bus and has a GpioInt
        if "I2cSerialBus" not in body:
            continue
        gi = _GPIOINT.search(body)
        if not gi:
            continue
        # this device's own props, not a child's — stop at the first nested Device
        shallow = body[: (m.start() if (m := re.search(r'\n\s*Device\s*\(', body)) else len(body))]
        if "GpioInt" not in shallow:
            continue

        hid = ""
        hm = _HID_RE.search(shallow)
        if hm:
            hid = (hm.group(1) or hm.group(2) or "").strip()
        if hid and not any(h in hid.upper() for h in _HID_HINTS) \
                and not hid.upper().startswith(("ELAN", "SYNA", "PNP", "ACPI")):
            continue

        pin_tok = gi.group(2).strip()
        try:
            pin = int(pin_tok, 16) if pin_tok.lower().startswith("0x") else int(pin_tok)
        except ValueError:
            continue
        path = _resolve_device_path(dsl, dm.start())
        if path is None:
            continue
        ctrl = gi.group(1).strip()
        if not ctrl.startswith("\\"):   # GPIO controllers are always root-anchored
            ctrl = "\\" + ctrl
        cands.append(GpioFinding(path=path, pin=pin, controller=ctrl,
                                 hid=hid or "PNP0C50"))

    # drop any device whose path is a strict prefix of another candidate's
    paths = {c.path for c in cands}
    return [c for c in cands
            if not any(p != c.path and p.startswith(c.path + ".") for p in paths)]


def _resolve_device_path(dsl: str, dev_pos: int) -> str | None:
    stack: list[str] = []
    depth = 0
    name_at: dict[int, str] = {}
    for mm in re.finditer(r'([{}])|(?:Device|Scope)\s*\(\s*([\\^A-Za-z0-9_.]+)\s*\)\s*\{', dsl):
        if mm.start() > dev_pos:
            break
        if mm.group(1) == "{":
            depth += 1
        elif mm.group(1) == "}":
            name_at.pop(depth, None)
            depth -= 1
        elif mm.group(2) is not None:
            depth += 1
            name_at[depth] = mm.group(2)
    stack = [name_at[d] for d in sorted(name_at)]
    if not stack:
        return None
    return _abspath(stack[:-1], stack[-1])


def generate(dsdt_dir: Path, ssdttime_dir: Path, out_dir: Path) -> GpioFinding | None:
    """Inspect the DSDT and, if one clear I2C-HID trackpad is found, compile
    SSDT-GPIO into ``out_dir``. Returns the finding (with ``generated`` set on
    success), or None when nothing usable was found."""
    iasl = _find_iasl(ssdttime_dir)
    if iasl is None:
        return None
    dsl = _decompile(dsdt_dir, iasl)
    if not dsl:
        return None
    found = _scan(dsl)
    if len(found) != 1:   # 0 = nothing; >1 = ambiguous, leave it manual
        return found[0] if found else None
    f = found[0]

    out_dir = out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    # ACPI resource strings want a doubled leading backslash for a root path
    (out_dir / "SSDT-GPIO.dsl").write_text(_TEMPLATE % {
        "path": f.path,
        "ctrl": f.controller.replace("\\", "\\\\"),
        "pin": f"0x{f.pin:02X}",
    })
    _iasl(iasl, out_dir, ["SSDT-GPIO.dsl"], timeout=60)
    aml = out_dir / "SSDT-GPIO.aml"
    # iasl can exit non-zero on benign warnings; trust a well-formed .aml
    if aml.is_file() and aml.read_bytes()[:4] == b"SSDT":
        f.generated = aml
    return f


if __name__ == "__main__":  # tiny manual harness: python -m ocforge.build.gpio <dsdt-dir> <ssdttime-dir>
    res = generate(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[1]) / "gpio-out")
    print(res.todo() if res else "no I2C-HID trackpad found in DSDT")
