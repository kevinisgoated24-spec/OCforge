"""Best-effort SSDT-GPIO for I2C-HID trackpads.

When a DSDT is available we decompile it (with the ``iasl`` SSDTTime already
fetched) and look for the touchpad: an I2C peripheral whose ``_CRS`` carries a
``GpioInt``. If exactly one confident candidate is found we render and compile
``SSDT-GPIO`` that re-asserts ``_STA`` and pins the interrupt; otherwise we hand
back a precise TODO (path + pin + controller) so the manual step is trivial.

Separately -- and independent of whether the touchpad device itself was
resolvable -- the GPIO *controller* the touchpad's interrupt is wired to
(e.g. ``\\_SB.GPI0``) often gates its own ``_STA``/``_HID`` behind a single
named variable, so Windows (Darwin isn't `_OSI`-recognized) sees a disguised
or degraded controller. Dortania's own manual guide documents this as two
known shapes -- ``GPEN`` and ``GPHD`` -- with the variable name and the
polarity that means "enabled" both varying per board. :func:`find_controller_gate`
detects this shape generically (whichever variable, whichever polarity) and
forces the enabled value under Darwin; this part needs no live hardware
value at all, unlike the touchpad's own GPIO pin.
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

# _HID / _CID values that mean "HID over I2C"
_HID_HINTS = ("PNP0C50", "ACPI0C50")

_TEMPLATE = '''\
// Generated by ocforge from the machine's DSDT. VERIFY the trackpad works;
// if not, this pin/controller is wrong -- redo it by hand.
DefinitionBlock ("", "SSDT", 2, "OCFORG", "GPIO", 0x00000000)
{
    External (%(path)s, DeviceObj)

    Scope (%(path)s)
    {
        Method (_STA, 0, NotSerialized)  // present, enabled, functioning
        {
            If (_OSI ("Darwin"))
            {
                Return (0x0F)
            }
            Return (Zero)
        }

        Name (RBUF, ResourceTemplate ()
        {
            GpioInt (Level, ActiveLow, ExclusiveAndWake, PullUp, 0x0000,
                "%(ctrl)s", 0x00, ResourceConsumer,,)
            {   // Pin list
                %(pin)s
            }
        })
    }
}
'''

# Written and compiled as its own SSDT-GPIOEN.dsl/.aml, *separate* from
# SSDT-GPIO.dsl above -- this iasl build fails to resolve externals at all
# (hard error, no .aml emitted) when two DefinitionBlocks are concatenated
# into one source file, even though each compiles cleanly standalone. The
# controller is a different device than the touchpad anyway (often not even
# the same parent), so a second OpenCore ACPI entry is the natural shape.
_GATE_TEMPLATE = '''\
// Generated by ocforge from the machine's DSDT -- forces the GPIO
// controller's own gating variable to its "fully enabled" value under
// Darwin. See SSDT-GPIO.aml's comment for the touchpad device itself.
DefinitionBlock ("", "SSDT", 2, "OCFORG", "GPIOEN", 0x00000000)
{
    External (%(ctrl)s, DeviceObj)
    External (%(var)s, IntObj)

    Scope (%(ctrl)s)
    {
        Method (_INI, 0, NotSerialized)
        {
            If (_OSI ("Darwin"))
            {
                %(var)s = %(value)s
            }
        }
    }
}'''


@dataclass
class GpioFinding:
    path: str          # full ACPI path of the touchpad device
    pin: int = 0
    controller: str = ""     # GPIO controller ACPI path
    hid: str = ""
    generated: Path | None = None   # compiled SSDT-GPIO.aml, if we made one
    # A device matching the known I2C-HID touchpad vendor hints was found,
    # but it builds its _CRS programmatically (helper methods, concatenated
    # buffers computed from board-variant globals) instead of a static
    # literal GpioInt/I2cSerialBus descriptor -- some OEM firmware shares
    # one DSDT across several board SKUs this way. Not something a text
    # scan of decompiled source can ever resolve (it would need a real ACPI
    # interpreter evaluating the method calls); distinct from "nothing
    # matching found at all" so the TODO says precisely what's going on
    # instead of looking identical to a DSDT with no touchpad device.
    dynamic: bool = False
    # (variable name, value to force) if the GPIO controller's own _STA/_HID
    # gates on one, per find_controller_gate() -- independent of whether the
    # touchpad device itself resolved; see module docstring.
    controller_gate: tuple[str, str] | None = None
    gate_generated: Path | None = None   # compiled SSDT-GPIOEN.aml, if we made one

    def todo(self) -> str:
        gate = ""
        if self.controller_gate:
            var, value = self.controller_gate
            made = f"; wrote {self.gate_generated.name}" if self.gate_generated else ""
            gate = (f" -- also: {self.controller} gates its own _STA/_HID on "
                    f"{var}; forcing {var} = {value} under Darwin{made}")
        if self.dynamic:
            return (f"SSDT-GPIO: touchpad {self.path} ({self.hid}) found, but its ACPI "
                    "resources are computed at runtime (helper methods / concatenated "
                    "buffers), not a static descriptor -- can't be generated from "
                    "decompiled source; see Dortania's manual SSDT-GPIO guide "
                    "(Getting-Started-With-ACPI > Laptops > trackpad-methods > manual)"
                    f"{gate}")
        made = f"; wrote {self.generated.name}" if self.generated else ""
        return (f"SSDT-GPIO: touchpad {self.path} ({self.hid}) -> GpioInt pin "
                f"0x{self.pin:02X} on {self.controller}{made}{gate}")


def _find_iasl(ssdttime_dir: Path) -> Path | None:
    names = ("iasl.exe", "iasl", "iasl-stable", "iasl-dev")
    for base in (ssdttime_dir / "Scripts", ssdttime_dir):
        for n in names:
            p = base / n
            if p.is_file():
                return p.resolve()
    return None


def _iasl(iasl: Path, work_dir: Path, args: list[str], timeout: int) -> None:
    """Run iasl with basename args so a relative ``work_dir`` can't double-nest."""
    subprocess.run([str(iasl), *args], cwd=str(work_dir.resolve()),
                   capture_output=True, text=True, timeout=timeout, check=False)


def _decompile(dsdt_dir: Path, iasl: Path) -> str | None:
    dsdt_dir = dsdt_dir.resolve()
    dsdt = dsdt_dir / "DSDT.aml"
    if not dsdt.is_file():
        return None
    ssdts = sorted(p.name for p in dsdt_dir.glob("SSDT*.aml"))
    args = ["-d"]
    if ssdts:
        args += ["-e", *ssdts]
    args.append("DSDT.aml")
    _iasl(iasl, dsdt_dir, args, timeout=120)
    dsl = dsdt.with_suffix(".dsl")
    return dsl.read_text(errors="replace") if dsl.is_file() else None


_GPIOINT = re.compile(
    r'GpioInt\s*\('           # opener
    r'[^)]*?"([^"]+)"'         # 1: GPIO controller path (first quoted arg)
    r'[^)]*?\)'               # ... rest of the descriptor args
    r'\s*\{[^}]*?'             # opening brace + any "// Pin list" comment
    r'(0x[0-9A-Fa-f]+|\d+)',   # 2: first pin number
    re.S,
)
_HID_RE = re.compile(
    r'_(?:HID|CID)\s*,\s*(?:"([^"]+)"|\w+\s*\(\s*"?([^")]+))'
)


def _abspath(stack: list[str], name: str) -> str | None:
    if name.startswith("^") or "^" in name:
        return None  # parent refs — don't guess
    if name.startswith("\\"):
        return name
    joined = ".".join(s.strip("\\") for s in [*stack, name] if s not in ("", "\\"))
    return "\\" + joined


def _scan(dsl: str) -> list[GpioFinding]:
    cands: list[GpioFinding] = []
    for dm in re.finditer(r'Device\s*\(\s*([\\^A-Za-z0-9_.]+)\s*\)\s*\{', dsl):
        start = dm.end()
        d, j = 1, start
        while j < len(dsl) and d:
            d += (dsl[j] == "{") - (dsl[j] == "}")
            j += 1
        body = dsl[start:j]
        # a peripheral, not a bus: it *consumes* an I2C bus and has a GpioInt
        if "I2cSerialBus" not in body:
            continue
        gi = _GPIOINT.search(body)
        if not gi:
            continue
        # this device's own props, not a child's — stop at the first nested Device
        shallow = body[: (m.start() if (m := re.search(r'\n\s*Device\s*\(', body)) else len(body))]
        if "GpioInt" not in shallow:
            continue

        hid = ""
        hm = _HID_RE.search(shallow)
        if hm:
            hid = (hm.group(1) or hm.group(2) or "").strip()
        if hid and not any(h in hid.upper() for h in _HID_HINTS) \
                and not hid.upper().startswith(("ELAN", "SYNA", "PNP", "ACPI")):
            continue

        pin_tok = gi.group(2).strip()
        try:
            pin = int(pin_tok, 16) if pin_tok.lower().startswith("0x") else int(pin_tok)
        except ValueError:
            continue
        path = _resolve_device_path(dsl, dm.start())
        if path is None:
            continue
        ctrl = gi.group(1).strip()
        if not ctrl.startswith("\\"):   # GPIO controllers are always root-anchored
            ctrl = "\\" + ctrl
        cands.append(GpioFinding(path=path, pin=pin, controller=ctrl,
                                 hid=hid or "PNP0C50"))

    # drop any device whose path is a strict prefix of another candidate's
    paths = {c.path for c in cands}
    return [c for c in cands
            if not any(p != c.path and p.startswith(c.path + ".") for p in paths)]


def _find_hid_hint_devices(dsl: str) -> list[tuple[str, str]]:
    """Devices matching a known I2C-HID touchpad vendor ID, with no
    I2cSerialBus/GpioInt requirement at all -- used only when :func:`_scan`
    finds nothing, to tell "no touchpad device in this DSDT" apart from
    "found one, but its resources aren't a static descriptor" (see
    GpioFinding.dynamic). Stricter than _scan's own HID match (no bare
    "PNP"/"ACPI" prefix) since there's no GpioInt/I2cSerialBus match to
    narrow things down first here -- those generic prefixes would catch
    far too much."""
    found: list[tuple[str, str]] = []
    for dm in re.finditer(r'Device\s*\(\s*([\\^A-Za-z0-9_.]+)\s*\)\s*\{', dsl):
        start = dm.end()
        d, j = 1, start
        while j < len(dsl) and d:
            d += (dsl[j] == "{") - (dsl[j] == "}")
            j += 1
        body = dsl[start:j]
        shallow = body[: (m.start() if (m := re.search(r'\n\s*Device\s*\(', body)) else len(body))]
        hm = _HID_RE.search(shallow)
        if not hm:
            continue
        hid = (hm.group(1) or hm.group(2) or "").strip()
        if not hid or not (any(h in hid.upper() for h in _HID_HINTS)
                           or hid.upper().startswith(("ELAN", "SYNA"))):
            continue
        path = _resolve_device_path(dsl, dm.start())
        if path is None:
            continue
        found.append((path, hid))
    paths = {p for p, _ in found}
    return [(p, h) for p, h in found if not any(q != p and q.startswith(p + ".") for q in paths)]


def _resolve_device_path(dsl: str, dev_pos: int) -> str | None:
    stack: list[str] = []
    depth = 0
    name_at: dict[int, str] = {}
    for mm in re.finditer(r'([{}])|(?:Device|Scope)\s*\(\s*([\\^A-Za-z0-9_.]+)\s*\)\s*\{', dsl):
        if mm.start() > dev_pos:
            break
        if mm.group(1) == "{":
            depth += 1
        elif mm.group(1) == "}":
            name_at.pop(depth, None)
            depth -= 1
        elif mm.group(2) is not None:
            depth += 1
            name_at[depth] = mm.group(2)
    stack = [name_at[d] for d in sorted(name_at)]
    if not stack:
        return None
    return _abspath(stack[:-1], stack[-1])


_STA_GATE = re.compile(
    r'Method\s*\(\s*_STA\s*,[^)]*\)\s*\{'
    r'\s*If\s*\(\(\s*([A-Za-z0-9_]{2,8})\s*==\s*(One|Zero)\s*\)\)\s*'
    r'\{\s*Return\s*\(\s*(0x[0-9A-Fa-f]+|Zero|One)\s*\)\s*\}'
    r'\s*Return\s*\(\s*(0x[0-9A-Fa-f]+|Zero|One)\s*\)',
    re.S,
)


def find_controller_gate(dsl: str, controller_path: str) -> tuple[str, str] | None:
    """For the GPIO controller device at ``controller_path``, detect Dortania's
    documented "a single variable gates this controller's own _STA" shape --
    ``If ((VAR == cond)) { Return (degraded) } Return (0x0F)`` -- whichever
    variable name and polarity the board uses (their guide shows two real
    examples, ``GPEN`` and ``GPHD``, with opposite polarity) and return
    ``(var, value_to_force)`` so forcing ``var = value_to_force`` under Darwin
    drives the *other* (0x0F, fully enabled) branch. None if this controller's
    _STA doesn't look like this shape -- most don't need the patch at all.
    """
    leaf = controller_path.rsplit(".", 1)[-1].lstrip("\\")
    if not leaf:
        return None
    for dm in re.finditer(r'Device\s*\(\s*' + re.escape(leaf) + r'\s*\)\s*\{', dsl):
        start = dm.end()
        d, j = 1, start
        while j < len(dsl) and d:
            d += (dsl[j] == "{") - (dsl[j] == "}")
            j += 1
        body = re.sub(r'//[^\n]*', '', dsl[start:j])  # strip iasl's trailing comments
        m = _STA_GATE.search(body)
        if not m:
            continue
        var, cond_val, _degraded, full = m.groups()
        if full != "0x0F":
            continue
        return var, ("Zero" if cond_val == "One" else "One")
    return None


def generate(dsdt_dir: Path, ssdttime_dir: Path, out_dir: Path) -> GpioFinding | None:
    """Inspect the DSDT and, if one clear I2C-HID trackpad is found, compile
    SSDT-GPIO into ``out_dir``. Returns the finding (with ``generated`` set on
    success), or None when nothing usable was found."""
    iasl = _find_iasl(ssdttime_dir)
    if iasl is None:
        return None
    dsl = _decompile(dsdt_dir, iasl)
    if not dsl:
        return None
    found = _scan(dsl)
    if len(found) != 1:   # 0 = nothing; >1 = ambiguous, leave it manual
        if found:
            f = found[0]
            f.controller_gate = find_controller_gate(dsl, f.controller)
            return f
        hinted = _find_hid_hint_devices(dsl)
        if hinted:
            path, hid = hinted[0]
            return GpioFinding(path=path, hid=hid, dynamic=True)
        return None
    f = found[0]
    f.controller_gate = find_controller_gate(dsl, f.controller)

    out_dir = out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    # ACPI resource strings want a doubled leading backslash for a root path
    (out_dir / "SSDT-GPIO.dsl").write_text(_TEMPLATE % {
        "path": f.path,
        "ctrl": f.controller.replace("\\", "\\\\"),
        "pin": f"0x{f.pin:02X}",
    })
    _iasl(iasl, out_dir, ["SSDT-GPIO.dsl"], timeout=60)
    aml = out_dir / "SSDT-GPIO.aml"
    # iasl can exit non-zero on benign warnings; trust a well-formed .aml
    if aml.is_file() and aml.read_bytes()[:4] == b"SSDT":
        f.generated = aml

    if f.controller_gate:
        var, value = f.controller_gate
        # Its own file/compile: two DefinitionBlocks concatenated into one
        # .dsl source fail every External resolution (hard error, no .aml),
        # even though each compiles cleanly on its own -- see _GATE_TEMPLATE.
        # Unlike _TEMPLATE's %(ctrl)s (inside a quoted GpioInt string, where
        # a doubled backslash is the escaped form), this one is a bare,
        # unquoted ACPI namestring in External(...)/Scope(...) -- a single
        # leading backslash, same as f.controller already is.
        (out_dir / "SSDT-GPIOEN.dsl").write_text(_GATE_TEMPLATE % {
            "ctrl": f.controller,
            "var": var,
            "value": value,
        })
        _iasl(iasl, out_dir, ["SSDT-GPIOEN.dsl"], timeout=60)
        gate_aml = out_dir / "SSDT-GPIOEN.aml"
        if gate_aml.is_file() and gate_aml.read_bytes()[:4] == b"SSDT":
            f.gate_generated = gate_aml
    return f


if __name__ == "__main__":  # tiny manual harness: python -m ocforge.build.gpio <dsdt-dir> <ssdttime-dir>
    res = generate(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[1]) / "gpio-out")
    print(res.todo() if res else "no I2C-HID trackpad found in DSDT")
